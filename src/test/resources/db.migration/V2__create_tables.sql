CREATE TABLE IF NOT EXISTS book_author
(
    book_id   BIGINT REFERENCES books (id) ON DELETE CASCADE,
    author_id VARCHAR(36) REFERENCES authors (id) ON DELETE CASCADE,
    PRIMARY KEY (book_id, author_id)
);
COMMENT ON TABLE book_author IS 'Join table for N-N relations between books and authors';

CREATE TABLE IF NOT EXISTS users
(
    id              VARCHAR(36) PRIMARY KEY NOT NULL,
    name            VARCHAR(150)        NOT NULL,
    email           VARCHAR(150) UNIQUE NOT NULL,
    phone           VARCHAR(20),
    password        VARCHAR(255) NOT NULL,
    status          VARCHAR(20) DEFAULT 'active' CHECK (status IN ('active', 'inactive', 'blocked')),
    inactive_since  TIMESTAMP DEFAULT NULL,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE users IS 'Table for all the users that uses the library';
COMMENT ON COLUMN users.id IS 'The user UUID internal identifier (generated by the application)';
COMMENT ON COLUMN users.name IS 'The user full title';
COMMENT ON COLUMN users.email IS 'The user email';
COMMENT ON COLUMN users.phone IS 'The user phone number';
COMMENT ON COLUMN users.password IS 'The user password (encrypted, obviously)';
COMMENT ON COLUMN users.status IS 'The user library status';
COMMENT ON COLUMN users.inactive_since IS 'The timestamp of when a user was inactive (soft-delete)';
COMMENT ON COLUMN users.created_at IS 'When the user was created';
COMMENT ON COLUMN users.updated_at IS 'When the user was updated';
