CREATE TABLE IF NOT EXISTS reservations
(
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id                  BIGINT REFERENCES books (id),
    user_id                  VARCHAR(36) REFERENCES users (id),
    reservation_date         DATE NOT NULL DEFAULT CURRENT_DATE,
    expected_devolution_date DATE NOT NULL,
    devolution_date          DATE,
    status                   VARCHAR(20)   DEFAULT 'active' CHECK (status IN ('active', 'returned', 'overdue')),
    observations             TEXT,
    created_at               TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    updated_at               TIMESTAMP     DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE reservations IS 'A 1-N table to associate books reservations with who reserved it';
COMMENT ON COLUMN reservations.id IS 'The id of the reservation (auto-generated)';
COMMENT ON COLUMN reservations.book_id IS 'The id of the reserved book';
COMMENT ON COLUMN reservations.user_id IS 'The UUID of the user who reserved the book';
COMMENT ON COLUMN reservations.reservation_date IS 'When the book was reserved';
COMMENT ON COLUMN reservations.expected_devolution_date IS 'When is the book is expected to be returned';
COMMENT ON COLUMN reservations.devolution_date IS 'When the book was really returned';
COMMENT ON COLUMN reservations.status IS 'The status of the reservation';
COMMENT ON COLUMN reservations.observations IS 'Some observations about the reservation';
COMMENT ON COLUMN reservations.created_at IS 'When the reservation was created';
COMMENT ON COLUMN reservations.updated_at IS 'When the reservation was updated';
GRANT SELECT, INSERT, UPDATE, DELETE ON reservations TO ${librarianRole};
GRANT SELECT, INSERT ON reservations TO ${userRole};

