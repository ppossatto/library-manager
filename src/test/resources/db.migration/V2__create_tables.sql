CREATE TABLE IF NOT EXISTS books
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(200) NOT NULL,
    isbn         VARCHAR(20) UNIQUE NOT NULL,
    publish_year INTEGER,
    edition      VARCHAR(50),
    synopsis     TEXT,
    total_pages  INTEGER,
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE books IS 'Table for all the books at the library';
COMMENT ON COLUMN books.id IS 'The book internal identifier (auto-generated)';
COMMENT ON COLUMN books.title IS 'The title of the book (obligatory)';
COMMENT ON COLUMN books.isbn IS 'The book International Standard Book Number (obligatory)';
COMMENT ON COLUMN books.publish_year IS 'The year when the book was published';
COMMENT ON COLUMN books.edition IS 'The book edition';
COMMENT ON COLUMN books.synopsis IS 'The synopsis of the book';
COMMENT ON COLUMN books.total_pages IS 'The amount of pages the book has';
COMMENT ON COLUMN books.created_at IS 'When the book was added to the database';
COMMENT ON COLUMN books.updated_at IS 'When the book was updated in the database';
